'use strict';
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'matrix-conversation-'));
process.env.DB_PATH = path.join(root, 'app.db');
const { db, initDb } = require('../src/db');
const { createMatrixConversationLedger } = require('../src/services/matrixConversationLedger');
const fixture = require('./fixtures/matrix-ledger/conversation-replay.json');
initDb();
db.prepare("INSERT INTO users (id,username,password,role,status,created_at) VALUES (9601,'ledger-user','x','foreign_trade_crm_admin','active','2026-07-18T00:00:00Z')").run();
const ledger = createMatrixConversationLedger({ db });
const base = { ...fixture, eventKind: 'message', direction: 'inbound', channel: 'bill', chatId: fixture.immutableChatId, threadId: fixture.immutableRootThreadId, platformMessageId: 'om_1', editVersion: 1, cardEventId: '', actorUserId: 9601, bindingId: '9611', normalizedText: 'Customer asks FOB. SMTP_PASS=must-not-store', attachmentRefs: [{ id: 'file-1', sha256: 'a'.repeat(64) }], bindings: { inquiryId: 8001, itemId: 1 }, occurredAt: '2026-07-18T00:00:00Z', source: { type: 'feishu_event', id: 'evt-1' }, idempotencyKey: 'event-1' };
const first = ledger.append(base);
assert.strictEqual(first.kind, 'created');
assert(!JSON.stringify(first).includes('must-not-store'));
const replay = ledger.append(base);
assert.strictEqual(replay.kind, 'replay');
assert.strictEqual(replay.event.id, first.event.id);
assert.throws(() => ledger.append({ ...base, normalizedText: 'changed', idempotencyKey: 'event-1' }), /idempotency conflict/i);
assert.throws(() => ledger.append({ ...base, conversationId: 'wrong', idempotencyKey: 'event-wrong' }), /conversation id mismatch/i);
const edit = ledger.append({ ...base, normalizedText: 'Customer asks FOB Shenzhen', editVersion: 2, idempotencyKey: 'event-edit-2' });
assert.notStrictEqual(edit.event.fingerprint, first.event.fingerprint);
assert.strictEqual(ledger.timeline({ inquiryId: 8001, limit: 10 }).rows.length, 2);
assert.strictEqual(ledger.requireEvent(first.event.id, first.event.fingerprint).id, first.event.id);
assert.throws(() => db.prepare("UPDATE matrix_conversation_events SET event_kind='changed' WHERE id=?").run(first.event.id), /append-only/i);
db.close(); fs.rmSync(root, { recursive: true, force: true });
console.log('PASS matrix conversation ledger');
